"""Render the weekly report as Markdown. Pure formatting: all numbers come from WeekTrends."""

from __future__ import annotations

from datetime import timedelta

from .recommend import KINDS, ThemeRecommendation
from .themes import ThemeSet
from .trends import (
    HISTORY_WEEKS,
    RISING_FACTOR,
    RISING_MIN_ISSUES,
    WeekTrends,
    parse_week,
)


def plural(n: int, word: str) -> str:
    return f"{n} {word}" if n == 1 else f"{n} {word}s"


def _issue_link(url: str) -> str:
    number = url.rstrip("/").rsplit("/", 1)[-1]
    return f"[#{number}]({url})"


def _ratio(t) -> str:
    if t.ratio is not None:
        return f"{t.ratio:.1f}x"
    return "new" if t.count else "-"


def _change(n: int) -> str:
    return f"+{n}" if n > 0 else str(n)


def render(repo: str, wt: WeekTrends, ts: ThemeSet,
           recs: list[ThemeRecommendation] | None, cost_line: str = "") -> str:
    names = {t.id: t.name for t in ts.themes}
    monday = parse_week(wt.week)
    sunday = monday + timedelta(days=6)
    rising = wt.rising()
    out = [
        f"# What's breaking: {repo}, {wt.week}",
        "",
        f"{monday:%d %b} - {sunday:%d %b %Y}. {wt.total_issues} issues opened; "
        f"{wt.total_issues - wt.unthemed} themed against themes.yaml version "
        f"{wt.themes_version}.",
        "",
    ]
    if wt.unthemed:
        out += [f"> {wt.unthemed} issues this week have no theme yet, so counts are low. "
                "Run `trends theme` and regenerate.", ""]
    if wt.missing_history:
        out += [f"> No issues stored for {', '.join(wt.missing_history)}; the averages "
                "treat those weeks as zero. Fetch more weeks for a fair comparison.", ""]
    if wt.unthemed_history:
        weeks = ", ".join(f"{w} ({n})" for w, n in wt.unthemed_history.items())
        out += [f"> Issues without a theme in earlier weeks: {weeks}. The averages count "
                "themed issues only, so they are too low. Run `trends theme` and regenerate.",
                ""]

    out += ["## Rising themes", ""]
    if rising:
        for t in rising:
            out.append(f"- **{names.get(t.theme, t.theme)}**: {t.count} issues, "
                       f"{HISTORY_WEEKS}-week average {t.average:.1f} ({_ratio(t)})")
    else:
        out.append("No theme is rising this week.")
    out += ["", f"Rising means at least {RISING_MIN_ISSUES} issues this week and at least "
            f"{RISING_FACTOR:g}x the average of the previous {HISTORY_WEEKS} weeks.", ""]

    out += ["## Recommendations", ""]
    if recs is None:
        out += ["Skipped (`--no-llm`).", ""]
    elif not recs:
        out += ["None: no rising themes (other than `other`).", ""]
    for rec in recs or []:
        out += [f"### {names.get(rec.theme, rec.theme)}", ""]
        for a in rec.actions:
            cites = ", ".join(_issue_link(u) for u in a.citations)
            out += [f"- **{KINDS[a.kind]}: {a.title}**  ", f"  {a.detail}  ",
                    f"  Based on: {cites}"]
        if not rec.actions:
            out.append("- No recommendation passed the citation check.")
        if rec.problems:
            out.append(f"- _Checks: {len(rec.problems)} problem(s) fixed or dropped: "
                       + "; ".join(rec.problems[:4]) + "_")
        out.append("")

    out += ["## All themes", "",
            f"| Theme | {wt.week} | Previous week | Change | {HISTORY_WEEKS}-week avg | "
            "vs avg | Rising |",
            "|---|---:|---:|---:|---:|---:|:---:|"]
    for t in wt.trends:
        out.append(f"| {names.get(t.theme, t.theme)} | {t.count} | {t.previous} | "
                   f"{_change(t.change)} | {t.average:.1f} | {_ratio(t)} | "
                   f"{'yes' if t.rising else ''} |")
    out.append(f"| **Total** | {sum(t.count for t in wt.trends)} | "
               f"{sum(t.previous for t in wt.trends)} | | | | |")

    out += ["", "## Most-reacted issues per theme", ""]
    for t in wt.trends:
        if not t.top_issues:
            continue
        out.append(f"**{names.get(t.theme, t.theme)}**")
        out.append("")
        for i in t.top_issues:
            out.append(f"- {_issue_link(i.url)} {i.title} ({plural(i.reactions, 'reaction')}, "
                       f"{plural(i.comments, 'comment')}, {i.state})")
        out.append("")

    out += ["## Weekly counts", "",
            "| Theme | " + " | ".join(wt.weeks) + " |",
            "|---|" + "---:|" * len(wt.weeks)]
    for t in wt.trends:
        out.append(f"| {names.get(t.theme, t.theme)} | "
                   + " | ".join(str(n) for n in t.history + [t.count]) + " |")

    out += ["", "---", "",
            f"Generated by support-trends-report. Themes: version {ts.version} "
            f"({len(ts.themes)} themes). Issue weeks are ISO weeks by creation date (UTC)."]
    if cost_line:
        out.append(cost_line)
    return "\n".join(out) + "\n"
